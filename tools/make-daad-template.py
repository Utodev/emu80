#!/usr/bin/env python3
"""Writes src/DaadTemplate.inc from DAAD Ready's empty English database
(BLANK_EN.DSF, by Stefan Vogt and Carlos Sanchez): the parts the DAAD
debugger takes when it converts a PAW game to a DAAD source (DSF): the
definitions before /CTL, the system messages and processes 0, 1, 2 and 6.

    make-daad-template.py <BLANK_EN.DSF> <output .inc>
"""
import re
import sys

lines = open(sys.argv[1], encoding='utf-8').read().replace('\r', '').split('\n')


def section(start, end):
    """Lines from the one matching start up to (not including) end."""
    i = next(n for n, l in enumerate(lines) if re.match(start, l))
    j = next(n for n in range(i + 1, len(lines)) if re.match(end, lines[n]))
    return lines[i:j]


def pas_array(name, items):
    out = ['  %s: array[0..%d] of string = (' % (name, len(items) - 1)]
    for n, s in enumerate(items):
        out.append("    '%s'%s" % (s.replace("'", "''"), ',' if n < len(items) - 1 else ');'))
    return out


header = section(r'; System flags', r'/CTL')
stx = {}
for l in section(r'/STX', r';-{10}'):
    m = re.match(r'/(\d+)\s+"(.*)"', l)
    if m:
        stx[int(m.group(1))] = m.group(2)
stx_list = [stx.get(n, '') for n in range(max(stx) + 1)]
pro = {n: section(r'/PRO %d\b' % n, r'/PRO %d\b|/END' % (n + 1)) for n in (0, 1, 2)}
pro[6] = section(r'/PRO 6\b', r'/END')

out = ['{ Generated by tools/make-daad-template.py from DAAD Ready\'s BLANK_EN.DSF:',
       '  do not edit. Used to convert PAW games to DAAD (DaadExport). }', 'const']
out += pas_array('TEMPLATE_HEADER', header)
out += pas_array('TEMPLATE_STX', stx_list)
for n in (0, 1, 2, 6):
    out += pas_array('TEMPLATE_PRO%d' % n, pro[n])
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
