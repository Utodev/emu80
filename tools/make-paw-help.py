#!/usr/bin/env python3
"""Writes src/PawHelp.inc from the PAW technical guide (PAW_MANUAL.html, the
HTML version of Gilsoft's manual): the description of every condact, shown
as a hint over a condact of a PAW game in the DAAD/PAW debugger.

    make-paw-help.py <PAW_MANUAL.html> <output .inc>
"""
import html
import re
import sys

# PAW's condacts (as in src/Daad.pas, PAW_CONDACT_NAMES)
NAMES = set('''AT NOTAT ATGT ATLT PRESENT ABSENT WORN NOTWORN CARRIED NOTCARR CHANCE ZERO
NOTZERO EQ GT LT ADJECT1 ADVERB INVEN DESC QUIT END DONE OK ANYKEY SAVE LOAD TURNS SCORE CLS
DROPALL AUTOG AUTOD AUTOW AUTOR PAUSE TIMEOUT GOTO MESSAGE REMOVE GET DROP WEAR DESTROY CREATE
SWAP PLACE SET CLEAR PLUS MINUS LET NEWLINE PRINT SYSMESS ISAT COPYOF COPYOO COPYFO COPYFF
LISTOBJ EXTERN RAMSAVE RAMLOAD BEEP PAPER INK BORDER PREP NOUN2 ADJECT2 ADD SUB PARSE LISTAT
PROCESS SAME MES CHARSET NOTEQ NOTSAME MODE LINE TIME PICTURE DOALL PROMPT GRAPHIC ISNOTAT
WEIGH PUTIN TAKEOUT NEWTEXT ABILITY WEIGHT RANDOM INPUT SAVEAT BACKAT PRINTAT WHATO RESET PUTO
NOTDONE AUTOP AUTOT MOVE PROTECT'''.split())

# Slips in the manual's text
HEADER_FIXES = {'ACGT': 'ATGT'}
TEXT_FIXES = [
    ('NOTWORN', 'Succeeds if Object objno. is carried.', 'Succeeds if Object objno. is not worn.'),
    ('ISAT', 'Succeeds if Object objno. is not at Location locno.',
     'Succeeds if Object objno. is at Location locno.'),
]

# Paragraphs that introduce the next group of condacts, not the last one
INTRO = re.compile(r'^(There |Now |Three |Two |One |Several |Thirteen|Four |The next |The two |'
                   r'A single |The true |Actions$|The following |Conditions$)')

raw = open(sys.argv[1], encoding='latin-1').read().replace('\r', '')
text = html.unescape(re.sub(r'<[^>]+>', '', raw))
lines = text.split('\n')
start = next(n for n, l in enumerate(lines) if l.strip() == 'The CondActs')
end = next(n for n in range(start, len(lines)) if lines[n].startswith('Detailed Description of the Database'))
lines = lines[start + 1:end]


def header(line):
    """The condact name if the line starts a condact's description"""
    if not line or line[0] in ' \t' or len(line) > 40:
        return None
    first = line.split()[0].rstrip('.')
    first = HEADER_FIXES.get(first, first)
    return first if first in NAMES else None


entries = []      # (name, syntax, [lines])
previous = ''
for line in lines:
    line = line.rstrip()
    # A condact's description starts after a blank line
    name = header(line) if previous.strip() == '' else None
    previous = line
    if name:
        syntax = line.replace(line.split()[0], name, 1)
        entries.append((name, syntax, []))
    elif entries:
        entries[-1][2].append(line)


def paragraphs(body):
    """Wrapped lines joined into paragraphs; tabbed lines (examples) kept as they are"""
    out, cur = [], []
    for line in body + ['']:
        if line.strip() == '':
            if cur:
                out.append(' '.join(cur))
                cur = []
        elif line.startswith('\t') or line.startswith('  '):
            if cur:
                out.append(' '.join(cur))
                cur = []
            out.append('  ' + re.sub(r'\s+', ' ', line.strip()))
        else:
            cur.append(line.strip())
    while out and INTRO.match(out[-1]):
        out.pop()
    return [re.sub(r' {2,}', ' ', p) if not p.startswith('  ') else p for p in out]


help_ = {}
for name, syntax, body in entries:
    paras = paragraphs(body)
    for fixname, old, new in TEXT_FIXES:
        if name == fixname:
            paras = [p.replace(old, new) for p in paras]
    if name not in help_:
        help_[name] = (syntax, paras)

# The manual's MES describes MESSAGE (its summary: MES has no newline,
# MESSAGE has one)
if 'MES' in help_ and 'MESSAGE' not in help_:
    help_['MESSAGE'] = ('MESSAGE mesno.', help_['MES'][1])
    help_['MES'] = ('MES mesno.', ['Prints Message mesno. in the current temporary colours, '
                                   'without a NEWLINE (MESSAGE adds one).'])

missing = sorted(NAMES - set(help_))
if missing:
    print('Not in the manual:', ' '.join(missing), file=sys.stderr)


def pas_string(s):
    out = []
    for n, line in enumerate(s.split('\n')):
        if n > 0:
            out.append('LineEnding')
        line = line.encode('ascii', 'replace').decode('ascii')
        for k in range(0, max(1, len(line)), 200):
            out.append("'%s'" % line[k:k + 200].replace("'", "''"))
    return ' +\n      '.join(out)


names = sorted(help_)
out = ['{ Generated by tools/make-paw-help.py from the PAW technical guide',
       '  (PAW_MANUAL.html): what each condact does in PAW }',
       'const',
       '  PAW_HELP_COUNT = %d;' % len(names),
       '  PAW_HELP_NAMES: array[0..PAW_HELP_COUNT - 1] of string = (']
for n, name in enumerate(names):
    out.append("    '%s'%s" % (name, ',' if n < len(names) - 1 else ');'))
out.append('  PAW_HELP_TEXTS: array[0..PAW_HELP_COUNT - 1] of string = (')
for n, name in enumerate(names):
    syntax, paras = help_[name]
    out.append('    ' + pas_string(syntax + '\n' + '\n'.join(paras)) +
               (',' if n < len(names) - 1 else ');'))
open(sys.argv[2], 'w', encoding='ascii', newline='\n').write('\n'.join(out) + '\n')
