#!/usr/bin/env python3
"""Writes src/DaadHelp.inc from the DAAD Ready documentation
(https://ngpaws.com/daadready/doc_en.html): the description of every
condact, shown as a hint over a condact in the DAAD/PAW debugger.

    make-daad-help.py <doc_en.html> <output .inc>
"""
import html
import re
import sys

page = open(sys.argv[1], encoding='utf-8').read()
parts = re.split(r'<condact>(.*?)</condact>', page, flags=re.S)


def clean(fragment):
    # Line breaks in the page's source are just spaces
    text = re.sub(r'\s*\n\s*', ' ', fragment)
    text = re.sub(r'<br\s*/?>', '\n', text)
    text = re.sub(r'</p>|<li>|</li>|</?ul>|</?code>', '\n', text)
    text = html.unescape(re.sub(r'<[^>]+>', '', text))
    text = text.replace('“', '"').replace('”', '"').replace('’', "'")
    text = text.replace('—', ' - ').replace('–', '-').replace(' ', ' ')
    text = re.sub(r'[ \t\r]+', ' ', text)
    return '\n'.join(l.strip() for l in text.split('\n') if l.strip())


# Name -> (syntax lines, text paragraphs); a condact described twice (MES
# with a number or a string...) gets both
help_ = {}
for i in range(1, len(parts), 2):
    syntax = clean(parts[i])
    if syntax.startswith('#'):
        continue        # compiler directives, not condacts
    body = re.split(r'<a name=|<h[1-6]|<p><u>', parts[i + 1])[0]
    text = clean(body)
    names = re.match(r'[A-Z0-9/]+', syntax).group(0).split('/')
    for name in names:
        syn, txt = help_.setdefault(name, ([], []))
        syn.append(syntax)
        if text and text not in txt:
            txt.append(text)


def pas_string(s):
    """A Pascal expression for s: chunks of up to 200 characters, lines
    joined with LineEnding."""
    out = []
    for n, line in enumerate(s.split('\n')):
        if n > 0:
            out.append('LineEnding')
        line = line.encode('ascii', 'replace').decode('ascii')
        for k in range(0, max(1, len(line)), 200):
            out.append("'%s'" % line[k:k + 200].replace("'", "''"))
    return ' +\n      '.join(out)


names = sorted(help_)
lines = ['{ Generated by tools/make-daad-help.py from the DAAD Ready documentation',
         '  (https://ngpaws.com/daadready/doc_en.html): what each condact does }',
         'const',
         '  DAAD_HELP_COUNT = %d;' % len(names),
         '  DAAD_HELP_NAMES: array[0..DAAD_HELP_COUNT - 1] of string = (']
for n, name in enumerate(names):
    lines.append("    '%s'%s" % (name, ',' if n < len(names) - 1 else ');'))
lines.append('  DAAD_HELP_TEXTS: array[0..DAAD_HELP_COUNT - 1] of string = (')
for n, name in enumerate(names):
    syn, txt = help_[name]
    lines.append('    ' + pas_string('\n'.join(syn) + '\n' + '\n'.join(txt)) +
                 (',' if n < len(names) - 1 else ');'))
open(sys.argv[2], 'w', encoding='ascii', newline='\n').write('\n'.join(lines) + '\n')
