#!/usr/bin/env python3
"""Builds roms/*.sym label files for the 128K, +2 and +3 ROMs from the
disassemblies in https://github.com/ZXSpectrumVault/rom-disassemblies

    tools/make-rom-symbols.py <rom-disassemblies checkout> <roms dir>

Names come from:
  - EQU / defc definitions of RAM addresses (system variables etc.),
  - routine titles in the comment banners of the 128K and +2 disassemblies
    ("; ===\\n; MASKABLE INTERRUPT ROUTINE\\n; ===" -> MASKABLE_INTERRUPT_ROUTINE),
  - the +3DOS jump block ("jp l062d ; DOS_OPEN").
Generic labels such as L0038 are left out: they only repeat the address.
"""
import os
import re
import sys

SOURCES = {
    '128-0.sym': 'Spectrum 128K/Spectrum128_ROM0.asm',
    'plus2-0.sym': 'Spectrum 128K +2/Spectrum+2_ROM0.asm',
    'plus3-0.sym': 'Spectrum 128K +3/Spectrum+3_V4-0_ROM0.asm',
    'plus3-1.sym': 'Spectrum 128K +3/Spectrum+3_V4-0_ROM1.asm',
    'plus3-2.sym': 'Spectrum 128K +3/Spectrum+3_V4-0_ROM2.asm',
    'plus3-3.sym': 'Spectrum 128K +3/Spectrum+3_V4-0_ROM3.asm',
}

LABEL = re.compile(r'^(?:L([0-9A-F]{4}):|\.l([0-9a-f]{4})\b)')
EQU = re.compile(r'^\s*([A-Za-z_][A-Za-z0-9_]*)\s+EQU\s+\$([0-9A-Fa-f]{1,4})\b', re.I)
DEFC = re.compile(r'^\s*defc\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*\$([0-9A-Fa-f]{1,4})\b', re.I)
JUMP = re.compile(r'^\.l([0-9a-f]{4})\s+jp\s+\S+\s*;\s*([A-Z][A-Z0-9_]+)\s*$')
RULE = re.compile(r'^;\s*[=\-*]{4,}\s*$')


def title_name(title):
    name = re.sub(r'\(.*?\)', '', title)
    name = re.sub(r'[^A-Za-z0-9]+', '_', name).strip('_').upper()
    if not name or name[0].isdigit():
        return None
    return name[:32]


def parse(path):
    symbols = {}       # address -> name
    names = set()
    lines = open(path, encoding='latin-1').read().split('\n')

    def add(addr, name):
        if name and addr not in symbols and name not in names:
            symbols[addr] = name
            names.add(name)

    pending = None     # banner title waiting for the next label
    for i, line in enumerate(lines):
        m = EQU.match(line) or DEFC.match(line)
        if m:
            # Constants below $4000 can point into another ROM (ROM 1 declares
            # +3DOS entry points to call them), so only RAM ones are kept
            if int(m.group(2), 16) >= 0x4000:
                add(int(m.group(2), 16), m.group(1))
            continue
        m = JUMP.match(line)
        if m:
            add(int(m.group(1), 16), m.group(2))
            continue
        # Banner: rule, one title line, rule
        if RULE.match(line) and i + 2 < len(lines) and RULE.match(lines[i + 2]):
            t = lines[i + 1].lstrip(';').strip()
            if t and not RULE.match(lines[i + 1]):
                pending = title_name(t)
            continue
        m = LABEL.match(line)
        if m and pending:
            add(int(m.group(1) or m.group(2), 16), pending)
            pending = None
    return symbols


def main():
    src, roms = sys.argv[1], sys.argv[2]
    for out, rel in SOURCES.items():
        symbols = parse(os.path.join(src, rel))
        with open(os.path.join(roms, out), 'w') as f:
            f.write('; Labels for %s, generated by tools/make-rom-symbols.py from\n' % out[:-4])
            f.write('; %s in github.com/ZXSpectrumVault/rom-disassemblies\n' % rel)
            f.write('; (disassemblies by Paul Farrow, Garry Lancaster and others).\n')
            for addr, name in sorted(symbols.items()):
                f.write('%s: EQU 0x%08X\n' % (name, addr))
        print('%-12s %4d symbols (%d below $4000)' % (
            out, len(symbols), sum(1 for a in symbols if a < 0x4000)))


if __name__ == '__main__':
    main()
