#!/usr/bin/env python3
"""Writes src/QuillHelp.inc from The Quill's manual (the text version typed
in by Paul Thompson): the description of every condition and action in
its "Detailed Description of the Interpreter" (4.1 AT locno. ... 6.37
AUTOR), shown as a hint over a condact of a Quill game in the Adventure
Debugger.

    make-quill-help.py <QuillAdventureSystemThe.txt> <output .inc>
"""
import re
import sys

lines = open(sys.argv[1], encoding='latin-1').read().replace('\r', '').split('\n')
start = next(n for n, l in enumerate(lines) if l.strip() == 'Detailed Description of the Interpreter')


def is_page_mark(line):
    return re.match(r'^-+\(\d+\)-+$', line.strip()) is not None


ITEM = re.compile(r'^\s+[46]\.\d+\s+([A-Z]+)(.*)$')
TOP = re.compile(r'^\d+\s+[A-Z]')

help_ = {}
current = None
for line in lines[start:]:
    if line.strip() == 'Detailed Description of the Database':
        break
    m = ITEM.match(line)
    if m:
        name = m.group(1)
        syntax = (name + ' ' + m.group(2).strip()).strip().rstrip('.').strip()
        current = [syntax, []]
        help_.setdefault(name, current)
        continue
    if current is None:
        continue
    if TOP.match(line) or '|' in line or re.match(r'^\s*-{3,}\s*$', line) or \
       (line.strip().startswith('-') and not is_page_mark(line)):
        current = None      # the next section, or a flowchart
        continue
    if is_page_mark(line):
        continue
    current[1].append(line.strip())


def paragraphs(body):
    out, cur = [], []
    for line in body + ['']:
        if line == '':
            if cur:
                out.append(' '.join(cur))
                cur = []
        else:
            cur.append(line)
    return [re.sub(r' {2,}', ' ', p) for p in out]


def pas_string(s):
    out = []
    for n, line in enumerate(s.split('\n')):
        if n > 0:
            out.append('LineEnding')
        line = line.encode('ascii', 'replace').decode('ascii')
        for k in range(0, max(1, len(line)), 200):
            out.append("'%s'" % line[k:k + 200].replace("'", "''"))
    return ' +\n      '.join(out)


names = sorted(help_)
out = ['{ Generated by tools/make-quill-help.py from The Quill\'s manual: what each',
       '  condition and action does }',
       'const',
       '  QUILL_HELP_COUNT = %d;' % len(names),
       '  QUILL_HELP_NAMES: array[0..QUILL_HELP_COUNT - 1] of string = (']
for n, name in enumerate(names):
    out.append("    '%s'%s" % (name, ',' if n < len(names) - 1 else ');'))
out.append('  QUILL_HELP_TEXTS: array[0..QUILL_HELP_COUNT - 1] of string = (')
for n, name in enumerate(names):
    syntax, body = help_[name]
    out.append('    ' + pas_string(syntax + '\n' + '\n'.join(paragraphs(body))) +
               (',' if n < len(names) - 1 else ');'))
open(sys.argv[2], 'w', encoding='ascii', newline='\n').write('\n'.join(out) + '\n')
print(len(names), 'condacts:', ' '.join(names))
